local fs = require 'scdn_sync.fs'
local store = fs.open(assert(arg[1]))
store:write('nested/state', 'first')
assert(store:read('nested/state') == 'first')
store:write('nested/state', 'second')
assert(store:read('nested/state') == 'second')
assert(not store:read('missing/child/state'))
assert(not pcall(store.read, store, 'nested/state', 2))
assert(not pcall(store.read, store, '../outside'))
assert(not pcall(store.read, store, 'escape/secret'))
assert(not pcall(fs.verify_directory, arg[1] .. '/escape'))
assert(not pcall(fs.verify_directory, arg[1] .. '/missing'))
local lock = store:lock('locks/one')
assert(not pcall(store.lock, store, 'locks/one'))
lock:release()
store:lock('locks/one'):release()
local listed = store:list('nested')
assert(#listed == 1 and listed[1] == 'state')
local reader = fs.reader(arg[1])
assert(reader:read('nested/state') == 'second')
assert(#reader:list() > 0)
assert(not reader:read('no-source/child'))
assert(not pcall(reader.list, reader, 'no-source'))
assert(not pcall(reader.write, reader, 'nested/state', 'forbidden'))
assert(not pcall(reader.remove, reader, 'nested/state'))
assert(not pcall(reader.lock, reader, 'nested/state'))
assert(not pcall(reader.read, reader, 'escape/secret'))
reader:close()
assert(not pcall(fs.reader, arg[1] .. '/no-source'))
store:remove('nested/state')
assert(not store:read('nested/state'))
print('filesystem checks passed')
